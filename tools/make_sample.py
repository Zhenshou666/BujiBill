WINDOW_DAYS = 30


def rand_time(days_ago_min: int = 0, days_ago_max: int = WINDOW_DAYS) -> datetime:
    d = random.randint(days_ago_min, days_ago_max)
    day = (END - timedelta(days=d)).date()
    return datetime(day.year, day.month, day.day,
                    random.randint(7, 22), random.randint(0, 59), random.randint(0, 59))


def rand_amount(lo: float, hi: float) -> str:
    """要凑出「有零头」的金额，全整数看着很假。"""
    return f"{random.uniform(lo, hi):.2f}"


